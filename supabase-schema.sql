-- ------------------------------------------------------------------- profiles
-- The resume-derived profile only: title, field, skills, matched roles.
-- The resume file itself is never stored.
create table if not exists public.profiles (
  user_id     uuid primary key references auth.users (id) on delete cascade,
  profile     jsonb not null,
  updated_at  timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "own profile: read"   on public.profiles;
drop policy if exists "own profile: write"  on public.profiles;
drop policy if exists "own profile: update" on public.profiles;
drop policy if exists "own profile: delete" on public.profiles;

create policy "own profile: read"   on public.profiles
  for select using (auth.uid() = user_id);
create policy "own profile: write"  on public.profiles
  for insert with check (auth.uid() = user_id);
create policy "own profile: update" on public.profiles
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own profile: delete" on public.profiles
  for delete using (auth.uid() = user_id);

-- --------------------------------------------------------- account deletion
-- Lets a signed-in person erase everything you hold about them, which most
-- privacy regimes require you to offer. Call from the client:
--   await sb.rpc('delete_my_data')
create or replace function public.delete_my_data()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.applications where user_id = auth.uid();
  delete from public.profiles     where user_id = auth.uid();
end;
$$;

revoke all on function public.delete_my_data() from public;
grant execute on function public.delete_my_data() to authenticated;
